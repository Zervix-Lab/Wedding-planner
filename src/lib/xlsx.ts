// Minimal .xlsx writer (server-only, no dependency). An .xlsx file is a zip of small XML files; we write exactly
// what Excel / Google Sheets / LibreOffice need: styled header, frozen header row, filters, number formats, totals.
import { deflateRawSync } from "node:zlib";

export type CellValue = string | number | null | undefined;

export interface SheetColumn {
  header: string;
  /** approximate width in characters */
  width?: number;
  /** numbers get a thousands separator and right alignment */
  number?: boolean;
}

export interface SheetData {
  name: string;
  columns: SheetColumn[];
  rows: CellValue[][];
  /** optional bold totals row under the data (not included in the filter range) */
  totals?: CellValue[];
}

/* ---------- XML helpers ---------- */
const esc = (s: string) =>
  s
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

function colName(i: number): string {
  let n = i + 1;
  let s = "";
  while (n > 0) {
    const r = (n - 1) % 26;
    s = String.fromCharCode(65 + r) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

// style ids (see STYLES below)
const S_HEADER = 1;
const S_TEXT = 2;
const S_NUMBER = 3;
const S_TOTAL_TEXT = 4;
const S_TOTAL_NUMBER = 5;

function cell(ref: string, v: CellValue, style: number): string {
  if (v === null || v === undefined || v === "") return `<c r="${ref}" s="${style}"/>`;
  if (typeof v === "number" && Number.isFinite(v)) return `<c r="${ref}" s="${style}"><v>${v}</v></c>`;
  return `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${esc(String(v))}</t></is></c>`;
}

function sheetXml(sheet: SheetData): string {
  const cols = sheet.columns;
  const lastCol = colName(Math.max(cols.length - 1, 0));
  const dataEnd = sheet.rows.length + 1;
  const rows: string[] = [];

  rows.push(`<row r="1" ht="28" customHeight="1">${cols.map((c, i) => cell(`${colName(i)}1`, c.header, S_HEADER)).join("")}</row>`);
  sheet.rows.forEach((r, ri) => {
    const n = ri + 2;
    rows.push(`<row r="${n}">${cols.map((c, i) => cell(`${colName(i)}${n}`, r[i], c.number ? S_NUMBER : S_TEXT)).join("")}</row>`);
  });
  if (sheet.totals) {
    const n = dataEnd + 1;
    const t = sheet.totals;
    rows.push(`<row r="${n}">${cols.map((c, i) => cell(`${colName(i)}${n}`, t[i], typeof t[i] === "number" ? S_TOTAL_NUMBER : S_TOTAL_TEXT)).join("")}</row>`);
  }

  const widths = cols.map((c, i) => `<col min="${i + 1}" max="${i + 1}" width="${c.width ?? 16}" customWidth="1"/>`).join("");
  return (
    `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` +
    `<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">` +
    `<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>` +
    `<sheetFormatPr defaultRowHeight="18"/>` +
    `<cols>${widths}</cols>` +
    `<sheetData>${rows.join("")}</sheetData>` +
    (sheet.rows.length > 0 ? `<autoFilter ref="A1:${lastCol}${dataEnd}"/>` : "") +
    `</worksheet>`
  );
}

